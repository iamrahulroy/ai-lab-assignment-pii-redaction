PROJECT_ROOT = Path(__file__).parents[1]
SOURCE_PATH = PROJECT_ROOT / "Red Herring Prospectus (3).docx"
DELIVERABLES = PROJECT_ROOT / "deliverables"


def test_evaluator_computes_exact_metrics_and_generated_report():
    text = "Alice emailed alice@example.com from 192.0.2.1."
    case = EvaluationCase(
        case_id="known-counts",
        text=text,
        entities=(
            _span(text, "PERSON", "Alice"),
            _span(text, "EMAIL_ADDRESS", "alice@example.com"),
            _span(text, "IP_ADDRESS", "192.0.2.1"),
        ),
    )
    predictions = (
        _detected(text, "PERSON", "Alice"),
        _detected(text, "EMAIL_ADDRESS", "alice@example.com"),
        _detected(text, "PHONE_NUMBER", "from"),
    )

    metrics = evaluate((case,), _StubDetector(predictions))
    report = render_report(
        {"prospectus": metrics, "synthetic": metrics, "combined": metrics}
    )

    assert (metrics.true_positives, metrics.false_positives) == (2, 1)
    assert (metrics.false_negatives, metrics.support) == (1, 3)
    assert metrics.precision == pytest.approx(2 / 3)
    assert metrics.recall == pytest.approx(2 / 3)
    assert metrics.f1 == pytest.approx(2 / 3)
    assert metrics.f2 == pytest.approx(2 / 3)
    assert metrics.token_accuracy == pytest.approx(3 / 5)
    assert metrics.residual_leakage_count == 1
    assert metrics.residual_leakage_rate == pytest.approx(1 / 3)
    assert metrics.per_type["IP_ADDRESS"].support == 1
    assert report.index("## Prospectus sample") < report.index(
        "## Synthetic absent-category cases"
    )
    assert report.index("## Synthetic absent-category cases") < report.index(
        "## Combined summary"
    )
    assert "Generated by `pii-redactor-evaluate`" in report


def test_supplied_docx_delivery_has_no_annotated_originals_and_linked_hashes():
    required = {
        PROJECT_ROOT / "README.md",
        PROJECT_ROOT / "evaluation_report.md",
        DELIVERABLES / "redacted_prospectus.docx",
        DELIVERABLES / "redaction_mapping.json.enc",
        DELIVERABLES / "audit_report.json",
    }
    assert all(path.is_file() for path in required)
    output_path = DELIVERABLES / "redacted_prospectus.docx"
    mapping_path = DELIVERABLES / "redaction_mapping.json.enc"
    audit = json.loads(
        (DELIVERABLES / "audit_report.json").read_text(encoding="utf-8")
    )

    assert zipfile.is_zipfile(output_path)
    with zipfile.ZipFile(output_path) as package:
        assert package.testzip() is None
        searchable = _searchable_values(package)
    Document(output_path)
    assert audit["status"] == "success"
    assert audit["source_sha256"] == _sha256(SOURCE_PATH)
    assert audit["output_sha256"] == _sha256(output_path)
    assert audit["mapping_sha256"] == _sha256(mapping_path)

    corpus = load_corpus(PROJECT_ROOT / "evaluation/annotations.json")
    originals = {
        case.text[entity.start : entity.end]
        for case in corpus["prospectus"]
        for entity in case.entities
    }
    assert all(value.casefold() not in searchable for value in originals)
    encrypted_mapping = mapping_path.read_bytes()
    assert all(value.encode() not in encrypted_mapping for value in originals)
    _assert_source_images_replaced(output_path)
    report = (PROJECT_ROOT / "evaluation_report.md").read_text(
        encoding="utf-8"
    )
    assert "Generated by `pii-redactor-evaluate`" in report


class _StubDetector:
    def __init__(self, predictions):
        self._predictions = predictions

    def detect(self, text):
        return self._predictions


def _span(text: str, entity_type: str, value: str) -> EntitySpan:
    start = text.index(value)
    return EntitySpan(entity_type, start, start + len(value))


def _detected(text: str, entity_type: str, value: str) -> DetectedEntity:
    span = _span(text, entity_type, value)
    return DetectedEntity(
        entity_type=entity_type,
        start=span.start,
        end=span.end,
        score=1.0,
        recognizer_name="stub",
    )


def _searchable_values(package: zipfile.ZipFile) -> str:
    values: list[str] = []
    for name in package.namelist():
        if not name.endswith((".xml", ".rels")):
            continue
        root = etree.fromstring(package.read(name))
        values.extend("".join(item.itertext()) for item in root.iter())
        values.extend(
            value for item in root.iter() for value in item.attrib.values()
        )
    return "\n".join(values).casefold()


def _assert_source_images_replaced(output_path: Path) -> None:
    with zipfile.ZipFile(SOURCE_PATH) as source, zipfile.ZipFile(
        output_path
    ) as output:
        source_media = {
            name: source.read(name)
            for name in source.namelist()
            if name.startswith("word/media/")
        }
        output_media = {
            name: output.read(name)
            for name in output.namelist()
            if name.startswith("word/media/")
        }
    assert source_media.keys() == output_media.keys()
    assert all(source_media[name] != output_media[name] for name in source_media)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()
