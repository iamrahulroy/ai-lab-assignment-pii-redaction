import argparse
import json
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from pii_redactor.bootstrap import build_pii_detector
from pii_redactor.domain import PiiDetector


TOKEN_PATTERN = re.compile(r"\S+")
DATASET_TITLES = {
    "prospectus": "Prospectus sample",
    "synthetic": "Synthetic absent-category cases",
    "combined": "Combined summary",
}


@dataclass(frozen=True, order=True)
class EntitySpan:
    entity_type: str
    start: int
    end: int


@dataclass(frozen=True)
class EvaluationCase:
    case_id: str
    text: str
    entities: tuple[EntitySpan, ...]


@dataclass(frozen=True)
class EntityMetrics:
    true_positives: int
    false_positives: int
    false_negatives: int
    support: int
    precision: float
    recall: float
    f1: float
    f2: float
    residual_leakage_count: int
    residual_leakage_rate: float


@dataclass(frozen=True)
class EvaluationMetrics(EntityMetrics):
    token_accuracy: float
    token_count: int
    per_type: Mapping[str, EntityMetrics]


def evaluate(
    cases: Sequence[EvaluationCase], detector: PiiDetector
) -> EvaluationMetrics:
    gold: set[tuple[str, EntitySpan]] = set()
    predicted: set[tuple[str, EntitySpan]] = set()
    correct_tokens = 0
    token_count = 0
    for case in cases:
        case_predictions = tuple(
            EntitySpan(item.entity_type, item.start, item.end)
            for item in detector.detect(case.text)
        )
        gold.update((case.case_id, item) for item in case.entities)
        predicted.update((case.case_id, item) for item in case_predictions)
        correct, total = _token_score(
            case.text, case.entities, case_predictions
        )
        correct_tokens += correct
        token_count += total

    entity_types = sorted(
        {item.entity_type for _, item in gold | predicted}
    )
    per_type = {
        entity_type: _entity_metrics(gold, predicted, entity_type)
        for entity_type in entity_types
    }
    overall = _entity_metrics(gold, predicted)
    return EvaluationMetrics(
        **overall.__dict__,
        token_accuracy=_safe_ratio(correct_tokens, token_count),
        token_count=token_count,
        per_type=per_type,
    )


def evaluate_corpus(
    corpus: Mapping[str, tuple[EvaluationCase, ...]], detector: PiiDetector
) -> dict[str, EvaluationMetrics]:
    results = {
        dataset: evaluate(cases, detector) for dataset, cases in corpus.items()
    }
    combined = tuple(case for cases in corpus.values() for case in cases)
    results["combined"] = evaluate(combined, detector)
    return results


def load_corpus(path: Path) -> dict[str, tuple[EvaluationCase, ...]]:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    datasets = payload.get("datasets")
    if not isinstance(datasets, dict):
        raise ValueError("Annotation file requires a datasets object")
    return {
        name: tuple(_load_case(item) for item in cases)
        for name, cases in datasets.items()
    }


def render_report(results: Mapping[str, EvaluationMetrics]) -> str:
    sections = [
        "<!-- Generated by `pii-redactor-evaluate`; do not edit manually. -->",
        "# PII Detection Evaluation Report",
        "",
        (
            "Exact entity metrics require both entity type and character span "
            "to match. Accuracy is token-label accuracy. Residual leakage is "
            "the share of annotated spans not fully covered by any prediction."
        ),
        "",
        (
            "The prospectus sample and synthetic absent-category cases are "
            "reported separately; the combined result is secondary."
        ),
    ]
    for dataset, metrics in results.items():
        sections.extend(_render_dataset(dataset, metrics))
    sections.extend(
        [
            "",
            "## Interpretation limits",
            "",
            (
                "This is a small stratified sample, not a statistically "
                "representative estimate for every page or document domain. "
                "Synthetic results demonstrate recognizer coverage but do not "
                "substitute for real-document annotations."
            ),
            "",
        ]
    )
    return "\n".join(sections)


def _entity_metrics(
    gold: set[tuple[str, EntitySpan]],
    predicted: set[tuple[str, EntitySpan]],
    entity_type: str | None = None,
) -> EntityMetrics:
    selected_gold = _select_type(gold, entity_type)
    selected_predicted = _select_type(predicted, entity_type)
    true_positives = len(selected_gold & selected_predicted)
    false_positives = len(selected_predicted - selected_gold)
    false_negatives = len(selected_gold - selected_predicted)
    precision = _safe_ratio(
        true_positives, true_positives + false_positives
    )
    recall = _safe_ratio(true_positives, true_positives + false_negatives)
    leaked = _residual_leakage(selected_gold, predicted)
    return EntityMetrics(
        true_positives=true_positives,
        false_positives=false_positives,
        false_negatives=false_negatives,
        support=len(selected_gold),
        precision=precision,
        recall=recall,
        f1=_f_beta(precision, recall, beta=1),
        f2=_f_beta(precision, recall, beta=2),
        residual_leakage_count=leaked,
        residual_leakage_rate=_safe_ratio(leaked, len(selected_gold)),
    )


def _select_type(
    entities: set[tuple[str, EntitySpan]], entity_type: str | None
) -> set[tuple[str, EntitySpan]]:
    if entity_type is None:
        return entities
    return {
        item for item in entities if item[1].entity_type == entity_type
    }


def _residual_leakage(
    gold: set[tuple[str, EntitySpan]],
    predicted: set[tuple[str, EntitySpan]],
) -> int:
    return sum(
        not any(
            case_id == predicted_case
            and prediction.start <= entity.start
            and prediction.end >= entity.end
            for predicted_case, prediction in predicted
        )
        for case_id, entity in gold
    )


def _token_score(
    text: str,
    gold: tuple[EntitySpan, ...],
    predicted: tuple[EntitySpan, ...],
) -> tuple[int, int]:
    tokens = tuple(TOKEN_PATTERN.finditer(text))
    correct = sum(
        _labels_for(token.start(), token.end(), gold)
        == _labels_for(token.start(), token.end(), predicted)
        for token in tokens
    )
    return correct, len(tokens)


def _labels_for(
    start: int, end: int, entities: tuple[EntitySpan, ...]
) -> frozenset[str]:
    return frozenset(
        item.entity_type
        for item in entities
        if item.start < end and start < item.end
    )


def _safe_ratio(numerator: int, denominator: int) -> float:
    return numerator / denominator if denominator else 0.0


def _f_beta(precision: float, recall: float, beta: int) -> float:
    denominator = beta**2 * precision + recall
    if not denominator:
        return 0.0
    return (1 + beta**2) * precision * recall / denominator


def _load_case(payload: dict[str, object]) -> EvaluationCase:
    text = str(payload["text"])
    entities = tuple(
        _load_entity(text, item) for item in payload.get("entities", [])
    )
    return EvaluationCase(
        case_id=str(payload["id"]), text=text, entities=entities
    )


def _load_entity(text: str, payload: dict[str, object]) -> EntitySpan:
    value = str(payload["value"])
    occurrence = int(payload.get("occurrence", 1))
    start = _find_occurrence(text, value, occurrence)
    return EntitySpan(str(payload["entity_type"]), start, start + len(value))


def _find_occurrence(text: str, value: str, occurrence: int) -> int:
    starts = tuple(match.start() for match in re.finditer(re.escape(value), text))
    if occurrence < 1 or occurrence > len(starts):
        raise ValueError("Annotated value occurrence is not present in case text")
    return starts[occurrence - 1]


def _render_dataset(dataset: str, metrics: EvaluationMetrics) -> list[str]:
    title = DATASET_TITLES.get(dataset, dataset.replace("_", " ").title())
    rows = [
        "",
        f"## {title}",
        "",
        "| Measure | Value |",
        "|---|---:|",
        f"| TP / FP / FN | {metrics.true_positives} / "
        f"{metrics.false_positives} / {metrics.false_negatives} |",
        f"| Support | {metrics.support} |",
        f"| Precision | {_format_metric(metrics.precision)} |",
        f"| Recall | {_format_metric(metrics.recall)} |",
        f"| F1 | {_format_metric(metrics.f1)} |",
        f"| F2 | {_format_metric(metrics.f2)} |",
        f"| Token accuracy | {_format_metric(metrics.token_accuracy)} |",
        f"| Residual leakage | {metrics.residual_leakage_count} / "
        f"{metrics.support} ({_format_metric(metrics.residual_leakage_rate)}) |",
        "",
        "| Entity type | Support | TP | FP | FN | Precision | Recall | F1 | F2 | Leakage |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    rows.extend(
        _render_type_row(entity_type, item)
        for entity_type, item in metrics.per_type.items()
    )
    return rows


def _render_type_row(entity_type: str, metrics: EntityMetrics) -> str:
    return (
        f"| {entity_type} | {metrics.support} | {metrics.true_positives} | "
        f"{metrics.false_positives} | {metrics.false_negatives} | "
        f"{_format_metric(metrics.precision)} | "
        f"{_format_metric(metrics.recall)} | {_format_metric(metrics.f1)} | "
        f"{_format_metric(metrics.f2)} | {metrics.residual_leakage_count} |"
    )


def _format_metric(value: float) -> str:
    return f"{value:.4f}"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="pii-redactor-evaluate",
        description="Generate exact-span PII evaluation metrics from annotations.",
    )
    parser.add_argument("--annotations", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    arguments = build_parser().parse_args(argv)
    corpus = load_corpus(arguments.annotations)
    results = evaluate_corpus(corpus, build_pii_detector())
    arguments.output.write_text(render_report(results), encoding="utf-8")
    return 0


def entrypoint() -> None:
    raise SystemExit(main())


if __name__ == "__main__":
    entrypoint()
